create table if not exists user_roles (
    id integer generated by default as identity primary key,
    role_name varchar(100) not null
);

create table if not exists positions (
    id integer generated by default as identity primary key,
    position_name varchar(120) not null
);

create table if not exists car_models (
    id integer generated by default as identity primary key,
    model_name varchar(120) not null,
    body_type varchar(80) not null,
    description varchar(500) not null,
    base_price numeric(12, 2) not null,
    release_year integer not null,
    available boolean not null
);

create table if not exists users (
    id integer generated by default as identity primary key,
    username varchar(50) not null,
    password varchar(100) not null,
    email varchar(120) not null,
    phone varchar(20) not null,
    role_id integer not null,
    position_id integer not null
);

create table if not exists car_complecttions (
    id integer generated by default as identity primary key,
    car_model_id integer not null,
    configuration_name varchar(120) not null,
    battery_capacity numeric(8, 2) not null,
    power_hp integer not null,
    range_km integer not null,
    max_speed integer not null,
    price numeric(12, 2) not null
);

create table if not exists cars_cards (
    id integer generated by default as identity primary key,
    user_id integer not null,
    created_at date not null,
    status varchar(100) not null
);

create table if not exists cars_card_details (
    id integer generated by default as identity primary key,
    card_id integer not null,
    complecttion_id integer not null,
    quantity integer not null,
    price numeric(12, 2) not null
);

create table if not exists dealers (
    id integer generated by default as identity primary key,
    dealer_name varchar(120) not null,
    city varchar(80) not null,
    address varchar(200) not null,
    phone varchar(20) not null,
    email varchar(120) not null,
    work_hours varchar(100) not null
);

create table if not exists news (
    id integer generated by default as identity primary key,
    title varchar(150) not null,
    content varchar(2000) not null,
    image varchar(255) not null,
    publish_date date not null,
    author_id integer not null
);

create table if not exists test_drives (
    id integer generated by default as identity primary key,
    user_id integer not null,
    car_model_id integer not null,
    dealer_id integer not null,
    test_drive_date date not null,
    status varchar(100) not null,
    comment varchar(255) not null
);



